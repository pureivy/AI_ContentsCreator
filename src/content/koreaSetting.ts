/**
 * 배경은 한국(2026-11-10 사장님 "특별한 언급이 없는 한 한국이 배경이야").
 * 웹툰 샘플 배경이 판자 울타리·짙은 박공지붕으로 일본풍으로 나왔다 — 그림 지시에 나라를 못박은 줄이 없었다.
 * 블로그·숏폼·카드뉴스 그림 지시가 같은 줄을 쓴다. 장면 글이 다른 나라를 말하면(일본 정원, 유럽 품종 농장 등) 붙이지 않는다.
 */
export const KOREA_SETTING =
  '[배경 — 한국] 특별히 다른 나라를 말하지 않는 한 배경은 한국이다. 바깥이면 한국 시골 마당·밭(낮은 돌담이나 시멘트 블록 담, 흰 회벽에 파란·빨간 함석지붕이나 기와지붕 단층집, 장독대, 텃밭, 멀리 낮은 산), 도시면 한국 아파트 베란다·골목·주택가. 판자 울타리, 일본식 집·툇마루·장지문, 서양 교외 주택·말뚝 울타리는 넣지 마라. 배경이 화면에 거의 없는 접사면 그대로 둔다.';

/** 묘목 지주(2026-11-10 사장님 — 웹툰 샘플 지주가 각목으로 그려졌다). 우리 농원·농가가 실제 쓰는 둥근 지주대. */
export const STAKE_LINE =
  '[지주] 어린 나무 지주는 실제 농가가 쓰는 둥근 지주다 — 초록 피복 쇠 지주대나 대나무 막대, 엄지 굵기의 둥근 단면. 네모난 각목·대패질한 나무 기둥·울타리 말뚝으로 그리지 마라.';

const FOREIGN = /일본|교토|미국|유럽|영국|프랑스|독일|이탈리아|네덜란드|중국|캐나다|호주|뉴질랜드|해외|외국|Japan|Japanese|American|Europe|English garden|China|Chinese/i;
const STAKE = /지주|지지대|말뚝|stake|support pole/i;

/** 장면 글이 다른 나라를 말하면 배경 줄은 빼고, 지주가 나오면 지주 줄을 더한다. */
export function koreaSettingLine(text: string): string {
  return [FOREIGN.test(text) ? '' : KOREA_SETTING, STAKE.test(text) ? STAKE_LINE : ''].filter(Boolean).join('\n');
}
